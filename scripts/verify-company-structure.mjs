import assert from 'node:assert/strict';
import {departmentStructure,isCompanyLeader,subordinateCount,personnelChartPeople,departmentHeads,visibleOrganizationEmployees} from '../src/lib/company-structure.js';
import {departmentHeadcount} from '../src/lib/recruitment-summary.js';

const leader={id:1,role:'employee',position:'Giám đốc',department_id:1};
const manager={id:2,role:'employee',position:'Trưởng nhóm kế toán tổng hợp',department_id:2,manager_id:1};
const staff={id:3,role:'director',position:null,department_id:2,manager_id:2};
assert.equal(isCompanyLeader(leader),true,'Business title must work without granting director permissions');
assert.equal(isCompanyLeader(staff),false,'A login role must not fabricate a business title');
assert.equal(isCompanyLeader({...leader,position:'Phó giám đốc tài chính'}),false,'Deputy must not become company director');
const structure=departmentStructure([leader,manager,staff],2);
assert.equal(structure.count,2);
assert.equal(structure.roots[0].title,manager.position);
assert.equal(structure.roots[0].children[0].title,null);
assert.equal(structure.roots[0].children[0].id,staff.id);
assert.equal(subordinateCount(structure.roots[0]),1,'Do not count the manager');
assert.equal(subordinateCount({id:10,children:[{id:11,children:[{id:12,children:[]}]}]}),2,'Include lower reporting levels');
assert.equal(subordinateCount({id:10,children:[]}),0);
assert(!JSON.stringify(structure).includes('full_name'));
assert.equal(departmentStructure([leader,manager,staff],99).count,0);
const cyclic=departmentStructure([{...manager,manager_id:3},{...staff,manager_id:2}],2);
assert.equal(cyclic.unresolved,2);
assert.equal(cyclic.roots.length,2);
const sales={id:8,name:'Phòng Kinh doanh'};
const director={id:20,role:'employee',position:'Giám đốc; Trưởng phòng Kinh doanh',department_id:1};
const salesperson={id:21,role:'employee',position:'Chuyên viên kinh doanh',department_id:8,manager_id:20};
const delegated=departmentStructure([director,salesperson],8,sales.name);
assert.equal(delegated.roots.length,1);
assert.equal(delegated.roots[0].title,'Trưởng phòng Kinh doanh');
assert.equal(delegated.roots[0].concurrent,true);
assert.equal(delegated.roots[0].children[0].id,21);
assert.equal(departmentStructure([director,salesperson],9,'Kế toán').count,0,'No invented delegation to other departments');
const chart=personnelChartPeople([director,salesperson],[sales]);
assert.equal(chart.length,3);
assert.equal(new Set(chart.map(p=>p.source_employee_id||p.id)).size,2);
const delegate=chart.find(p=>p.delegated);
assert.equal(delegate.manager_id,director.id);
assert.equal(chart.find(p=>p.id===21).manager_id,delegate.id);
assert.equal(departmentHeadcount([director,salesperson],8,[]).current,1,'Projection must not double-count headcount');
assert.equal(departmentHeadcount([director,salesperson],8,[],sales.name).current,2,'Count delegated manager once in the department');
const executive={...director,position:'Giám  đốc điều hành; Trưởng phòng Kinh doanh'};
assert.equal(isCompanyLeader(executive),true);
const vacantSales=departmentStructure([executive],sales.id,sales.name);
assert.equal(departmentHeads(vacantSales).length,1,'Concurrent head remains visible with zero subordinates');
assert.equal(departmentHeads(vacantSales)[0].title,'Trưởng phòng Kinh doanh');
assert.equal(departmentHeads(vacantSales)[0].children.length,0);
const soloManager={...manager,manager_id:executive.id};
assert.equal(departmentHeads(departmentStructure([executive,soloManager],2,'Kế toán')).length,1,'Department head remains visible without staff');
const typedTitle={...soloManager,position:'Trường phòng Tài chính doanh nghiệp'};
assert.equal(departmentHeads(departmentStructure([typedTitle],2,'Tài chính'))[0].title,typedTitle.position,'Preserve entered job title');
const accountant={id:40,role:'employee',position:'Kế toán; Chuyên viên — Phòng Kinh doanh',department_id:2,manager_id:null};
const salesColleague={...salesperson,id:41,manager_id:40};
const staffChart=personnelChartPeople([accountant,salesColleague],[sales,{id:2,name:'Kế toán'}]);
assert.equal(staffChart.length,3,'Any employee can have a second departmental position');
assert.equal(staffChart.find(p=>p.id===41).manager_id,'40:department:8');
assert.equal(departmentStructure([accountant],8,sales.name).roots[0].id,40);
assert.equal(departmentHeadcount([accountant,salesColleague],8,[],sales.name).current,2);
assert.equal(departmentHeadcount([accountant],2,[],'Kế toán').current,1);
assert.equal(departmentHeads(departmentStructure([accountant],8,sales.name)).length,0,'A concurrent specialist is not automatically a department head');
assert.equal(departmentStructure([accountant],3,'Nhân sự').count,0,'No inferred position in unrelated departments');
assert.equal(departmentStructure([{...accountant,position:'Kế toán'}],8,sales.name).count,0,'Single primary title does not create a second job');
assert.deepEqual(visibleOrganizationEmployees([accountant,salesColleague,{...manager,id:50}],[sales],{department_id:8},false).map(e=>e.id),[40,41]);
assert.deepEqual(visibleOrganizationEmployees([{...accountant,department_id:null}],[],{department_id:null},false),[],'Unassigned users cannot see all unassigned staff');
console.log('PASS: actual business titles, management hierarchy, missing data, privacy, empty departments and cycles');
