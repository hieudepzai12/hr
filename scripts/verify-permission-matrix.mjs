import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import bcrypt from 'bcryptjs';
import pg from 'pg';
import { ACTION_MODULES, defaultPermissions, effectivePermissions, permissionForRequest } from '../src/lib/permissions.js';
import { moduleActions } from '../src/lib/governance-config.js';

const connection=process.env.DATABASE_URL;
const base=process.env.VERIFY_BASE_URL;
if(!connection||!base||![connection,base].every(value=>['localhost','127.0.0.1'].includes(new URL(value).hostname)))throw new Error('Local verification only');
const db=new pg.Client({connectionString:connection});await db.connect();
const suffix=randomUUID().slice(0,8),role=`custom_matrix_${suffix}`,password=randomUUID()+randomUUID();
const employees=[],departments=[];
let admin,actor,target,taskId;
const call=async(path,cookie,method='GET',body)=>{
  const response=await fetch(base+'/api'+path,{method,headers:{cookie:cookie||'',...(body?{'content-type':'application/json'}:{})},body:body?JSON.stringify(body):undefined});
  return {status:response.status,data:await response.json().catch(()=>({})),cookie:response.headers.get('set-cookie')?.split(';')[0]};
};
const expect=async(path,cookie,method,body,status)=>{const result=await call(path,cookie,method,body);assert.equal(result.status,status,`${method} ${path}: ${JSON.stringify(result.data)}`);return result.data;};
const grants=(module,actions)=>{
  const p=defaultPermissions(role);
  p[module]={...p[module],...Object.fromEntries(ACTION_MODULES[module].map(action=>[action,actions.includes(action)]))};
  p[module].manage=actions.some(action=>action!=='view');if(p[module].manage)p[module].view=true;
  return p;
};
const configure=permissions=>expect('/permissions',admin.cookie,'PUT',{role,permissions},200);
try{
  const legacy=effectivePermissions('custom_legacy',{employees:{view:true,manage:true},kpi:{view:true,manage:true},tasks:{view:true,manage:true}});
  assert.ok(legacy.accounts.view&&legacy.accounts.create&&legacy.accounts.deactivate&&legacy.kpi.edit&&legacy.kpi.delete);
  assert.equal(legacy.accounts.reset_password,false,'Legacy manager grants do not gain password reset');
  assert.equal(legacy.tasks.scopes.comment,legacy.tasks.scopes.approve);
  const defaults=defaultPermissions('employee');assert.equal(defaults.accounts.view,false);assert.equal(defaults.kpi.edit,false);
  assert.ok(!moduleActions('customers').includes('approve')&&!moduleActions('customers').includes('restore'));
  assert.ok(!moduleActions('reports').includes('approve'));assert.ok(moduleActions('tasks').includes('comment'));
  assert.deepEqual(permissionForRequest('/api/kpi/1','PUT'),['kpi','edit']);
  assert.deepEqual(permissionForRequest('/api/employees/1/reset-password','POST'),['accounts','reset_password']);
  departments.push((await db.query('INSERT INTO departments(name) VALUES($1) RETURNING id',[`Matrix ${suffix}`])).rows[0].id);
  await db.query('INSERT INTO role_permissions(role,label,permissions) VALUES($1,$2,$3)',[role,`Matrix ${suffix}`,JSON.stringify(defaultPermissions(role))]);
  const hash=await bcrypt.hash(password,10);
  for(const key of ['admin','actor','target']){
    const email=`matrix-${key}-${suffix}@example.invalid`;
    const row=(await db.query('INSERT INTO employees(full_name,email,password_hash,role,department_id) VALUES($1,$2,$3,$4,$5) RETURNING id',
    [`Matrix ${key}`,email,hash,key==='actor'?role:key==='admin'?'admin':'employee',departments[0]])).rows[0];
    employees.push(row.id);
    const login=await call('/auth/login','','POST',{email,password});assert.equal(login.status,200);
    if(key==='admin')admin={...row,cookie:login.cookie};else if(key==='actor')actor={...row,cookie:login.cookie};else target={...row,cookie:login.cookie};
  }
  taskId=(await db.query("INSERT INTO tasks(title,assignee_id,created_by,department_id,status) VALUES('Matrix task',$1,$2,$3,'review') RETURNING id",[target.id,admin.id,departments[0]])).rows[0].id;
  await expect('/reports',target.cookie,'POST',{title:'Matrix report',content:'Local permission fixture',status:'submitted',task_ids:[taskId]},201);
  const kpiBody={employee_id:target.id,period:`Matrix ${suffix}`,rating:'Hoàn thành'};
  const kpi=await expect('/kpi',admin.cookie,'POST',kpiBody,201);
  await expect('/permissions',actor.cookie,'GET',undefined,403);
  await expect('/permissions',actor.cookie,'PUT',{role,permissions:defaultPermissions(role)},403);
  await configure(grants('kpi',['view']));
  await expect('/kpi',actor.cookie,'GET',undefined,200);
  await expect('/kpi',actor.cookie,'POST',kpiBody,403);
  await expect(`/kpi/${kpi.id}`,actor.cookie,'PUT',kpiBody,403);
  await expect(`/kpi/${kpi.id}`,actor.cookie,'DELETE',undefined,403);
  await configure(grants('kpi',['view','edit']));
  await expect(`/kpi/${kpi.id}`,actor.cookie,'PUT',{...kpiBody,comments:'Edit only'},200);
  await expect('/kpi',actor.cookie,'POST',kpiBody,403);
  await expect(`/kpi/${kpi.id}`,actor.cookie,'DELETE',undefined,403);
  await configure(grants('kpi',['view','create']));
  const created=await expect('/kpi',actor.cookie,'POST',kpiBody,201);
  await expect(`/kpi/${created.id}`,actor.cookie,'PUT',kpiBody,403);
  await configure(grants('kpi',['view','delete']));
  await expect(`/kpi/${created.id}`,actor.cookie,'DELETE',undefined,200);
  await expect(`/kpi/${kpi.id}`,actor.cookie,'PUT',kpiBody,403);
  await configure(grants('departments',['view']));
  await expect('/departments',actor.cookie,'GET',undefined,200);
  await expect('/departments',actor.cookie,'POST',{name:'Denied'},403);
  await expect(`/departments/${departments[0]}`,actor.cookie,'PUT',{name:'Denied'},403);
  await configure(grants('departments',['view','edit']));
  await expect(`/departments/${departments[0]}`,actor.cookie,'PUT',{name:`Matrix updated ${suffix}`},200);
  await expect(`/departments/${departments[0]}`,actor.cookie,'DELETE',undefined,403);
  await configure(grants('departments',['view','create']));
  const department=await expect('/departments',actor.cookie,'POST',{name:`Matrix extra ${suffix}`},201);departments.push(department.id);
  await configure(grants('departments',['view','delete']));
  await expect(`/departments/${department.id}`,actor.cookie,'DELETE',undefined,200);
  await configure(grants('accounts',['view']));
  await expect('/employees?accounts=1',actor.cookie,'GET',undefined,200);
  await expect('/employees',actor.cookie,'GET',undefined,403);
  const newAccount={full_name:`Matrix new ${suffix}`,email:`matrix-new-${suffix}@example.invalid`,password,role:'employee',department_id:departments[0]};
  await expect('/employees',actor.cookie,'POST',newAccount,403);
  await configure(grants('accounts',['view','create']));
  const account=await expect('/employees',actor.cookie,'POST',newAccount,201);employees.push(account.id);
  await expect('/employees?fields=options',actor.cookie,'GET',undefined,200);
  await expect('/departments?options=1',actor.cookie,'GET',undefined,200);
  await expect('/employees',actor.cookie,'POST',{...newAccount,email:`matrix-admin-${suffix}@example.invalid`,role:'admin'},403);
  await expect(`/employees/${account.id}`,actor.cookie,'DELETE',undefined,403);
  await expect(`/employees/${account.id}/reset-password`,actor.cookie,'POST',{new_password:password},403);
  await configure(grants('accounts',['view','reset_password']));
  await expect(`/employees/${account.id}/reset-password`,actor.cookie,'POST',{new_password:password},200);
  await expect(`/employees/${admin.id}/reset-password`,actor.cookie,'POST',{new_password:password},403);
  await configure(grants('accounts',['view','deactivate']));
  await expect(`/employees/${account.id}`,actor.cookie,'DELETE',undefined,200);
  await expect(`/employees/${account.id}`,actor.cookie,'PATCH',{status:'active'},403);
  await configure(grants('accounts',['view','restore']));
  await expect(`/employees/${account.id}`,actor.cookie,'PATCH',{status:'active'},200);
  await expect(`/employees/${account.id}`,actor.cookie,'DELETE',undefined,403);
  await configure(grants('employees',['view','edit']));
  await expect('/employees?accounts=1',actor.cookie,'GET',undefined,403,'Staff editing does not grant account administration');
  const staffBody={full_name:'Matrix employee edited',role:'employee',status:'active',department_id:departments[0]};
  await expect(`/employees/${account.id}`,actor.cookie,'PUT',staffBody,200);
  await expect(`/employees/${account.id}`,actor.cookie,'PUT',{...staffBody,status:'inactive'},403);
  await expect(`/employees/${account.id}`,actor.cookie,'DELETE',undefined,403);
  const comment=defaultPermissions(role);
  comment.tasks.scopes={...comment.tasks.scopes,view:'all',comment:'all'};comment.tasks.view=true;comment.tasks.manage=true;
  comment.reports.scopes.view='all';comment.reports.view=true;
  await configure(comment);
  await expect(`/tasks/${taskId}/opinion`,actor.cookie,'POST',{opinion:'Comment only'},200);
  await expect(`/tasks/${taskId}/review`,actor.cookie,'POST',{decision:'approved',opinion:'Denied acceptance'},403);
  comment.tasks.scopes.comment='none';comment.tasks.scopes.approve='all';
  await configure(comment);
  await expect(`/tasks/${taskId}/opinion`,actor.cookie,'POST',{opinion:'Denied comment'},403);
  await expect(`/tasks/${taskId}/review`,actor.cookie,'POST',{decision:'approved',opinion:'Acceptance only'},200);
  await configure(defaultPermissions(role));
  await expect(`/kpi/${kpi.id}`,actor.cookie,'PUT',kpiBody,403,'Revoked permissions take effect with the existing cookie');
  console.log('PASS: independent KPI, department, staff, account and leader-comment permissions; API enforcement, immediate revocation and legacy compatibility.');
}finally{
  if(employees.length){
    await db.query('DELETE FROM audit_logs WHERE actor_id=ANY($1::int[])',[employees]);
    await db.query('DELETE FROM kpi_evaluations WHERE employee_id=ANY($1::int[]) OR evaluated_by=ANY($1::int[])',[employees]);
    await db.query('DELETE FROM reports WHERE employee_id=ANY($1::int[])',[employees]);
    await db.query('DELETE FROM tasks WHERE created_by=ANY($1::int[])',[employees]);
    await db.query('DELETE FROM employees WHERE id=ANY($1::int[])',[employees]);
  }
  await db.query('DELETE FROM role_permissions WHERE role=$1',[role]);
  await db.query('DELETE FROM departments WHERE id=ANY($1::int[])',[departments]);await db.end();
}
